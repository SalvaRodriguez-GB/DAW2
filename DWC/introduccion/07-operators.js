// Operadores aritméticos

let a = 5;
let b = 10;

console.log(a + b); //Suma
console.log(a - b); // Resta
console.log(a / b); // División
console.log(a * b); // Multiplicación

console.log(a % b); // Módulo o resto de la división
console.log(a ** b); // Exponente

a++; //Incremento
console.log(a);
console.log(++a);

b--; ///Decremento
console.log(b);
console.log(--b);

//Operadores de asignación

let myVariable = 2;

console.log(myVariable); // Suma de asignación
myVariable += 2;
console.log(myVariable);
console.log(myVariable); // Resta de asignación
myVariable -= 2;
console.log(myVariable);
console.log(myVariable); // Multiplicación de asignación
myVariable *= 2;
console.log(myVariable);
console.log(myVariable); // División de asignación
myVariable /= 2;
console.log(myVariable);
console.log(myVariable); // Módulo de asignación
myVariable %= 2;
console.log(myVariable);

// Operadores de comparación

console.log(a > b); // Mayor que
console.log(a < b); // Menor que
console.log(a >= b); // Mayor o igual que
console.log(a <= b); // Menor o igual que
console.log(a == b); // Igualdad
console.log(a != b); // Desigualdad
console.log(a === b); // Igualdad estricta
console.log(a !== b); // Desigualdad estricta



